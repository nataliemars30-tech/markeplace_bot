_rules: Dict[str, Dict[str, str]] | None = None


def _seed_missing(ws, existing: set) -> int:
    """Дописать в лист строки DEFAULTS, которых там ещё нет (раздел+ключ)."""
    added = 0
    batch = []
    for section, kv in DEFAULTS.items():
        for key, value in kv.items():
            if (section, key) not in existing:
                batch.append([section, key, value])
                added += 1
    if batch:
        ws.append_rows(batch, value_input_option="RAW")
    return added


def load_rules(force: bool = False) -> Dict[str, Dict[str, str]]:
    """Загрузка правил из листа «Правила». При сбое — DEFAULTS."""
    global _rules
    if _rules is not None and not force:
        return _rules
    rules = {s: dict(kv) for s, kv in DEFAULTS.items()}
    try:
        manager = GoogleSheetsManager()
        client = manager._get_client()
        spreadsheet = client.open_by_key(manager.spreadsheet_key) if manager.spreadsheet_key \
            else client.open("Каталог REN")
        try:
            ws = spreadsheet.worksheet(SHEET_NAME)
        except Exception:
            ws = spreadsheet.add_worksheet(title=SHEET_NAME, rows=300, cols=len(HEADERS))
            ws.append_row(HEADERS)
            _seed_missing(ws, set())
            logger.info("Лист «Правила» создан и заполнен значениями по умолчанию")
        values = ws.get_all_values()
        existing = set()
        for row in values[1:]:
            if len(row) < 3 or not row[0].strip():
                continue
            existing.add((row[0].strip(), row[1].strip()))
            rules.setdefault(row[0].strip(), {})[row[1].strip()] = row[2].strip()
        added = _seed_missing(ws, existing)
        if added:
            logger.info(f"Лист «Правила»: дописано {added} недостающих граф")
        # убрать устаревшие английские строки, если рядом уже есть русская версия
        to_delete = []
        for idx, row in enumerate(values[1:], start=2):
            if len(row) < 2:
                continue
            sec, key = row[0].strip(), row[1].strip()
            for (rsec, ru), old in ALIASES.items():
                if sec == rsec and key == old and (rsec, ru) in existing:
                    to_delete.append(idx)
                    break
        for idx in reversed(to_delete):
            ws.delete_rows(idx)
        if to_delete:
            logger.info(f"Лист «Правила»: удалено устаревших строк: {len(to_delete)}")
        logger.info(f"Правила загружены из таблицы: {sum(len(v) for v in rules.values())} значений")
    except Exception as e:
        logger.warning(f"Лист «Правила» недоступен ({e}) — использую значения по умолчанию")
    _rules = rules
    return rules


def get(section: str, key: str, default: str = "") -> str:
    rules = load_rules()
    if key in rules.get(section, {}):
        return rules[section][key]
    alias = ALIASES.get((section, key))
    if alias and alias in rules.get(section, {}):
        return rules[section][alias]
    return default


def reload_rules() -> Dict[str, Dict[str, str]]:
    return load_rules(force=True)
