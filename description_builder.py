# Расходники и упаковка — исключаются из списка цветов (ТЗ)
EXCLUDE_WORDS = (
    "упаковка", "пленка", "плёнка", "лента", "кризал", "аквабокс", "открытка",
    "коробка", "оазис", "корзина", "тишью", "корейка", "фоамиран", "бант",
    "секатор", "подкормка", "транспортировочный",
)


def build_individual_care(cleaned_flowers: List[str]) -> str:
    """Подбирает 1-2 точечных совета по уходу строго под цветы из состава букета."""
    matched: List[str] = []
    flowers_lower = [f.lower() for f in cleaned_flowers]
    for key_flower, tip in CARE_RULES.items():
        if any(key_flower in fl for fl in flowers_lower):
            if tip not in matched:
                matched.append(tip)
            if len(matched) >= 2:
                break
    if not matched:
        return (
            "Перед постановкой в вазу обновите срез стеблей на 1–2 см под углом и используйте "
            "чистую прохладную воду. Держите букет вдали от прямого солнца, сквозняков и батарей."
        )
    return " ".join(matched)


def generate_marketplace_description(
    bouquet_name: str,
    product_type: str,        # "author" или "mono"
    color_or_season: str,     # цвет/категория из меню бота
    positions: List[Dict[str, Any]],
    packaging_type: str,      # "Пленка" или "Под ленту"
    platform: str = "flowwow"  # "market" — по правилам Яндекс Маркета: БЕЗ эмодзи, <br>, без региона/доставки
) -> str:
    """Эталонное SEO-описание. Для Flowwow/Еды — с эмодзи и гео-ключами;
    для Маркета — строго по официальным правилам (эмодзи запрещены, переносы через <br>,
    нельзя регион, доставку, «купить»)."""
    market = platform == "market"
    type_label = "Моно" if product_type == "mono" else "Авторский"
    mood = MOOD_BY_COLOR.get(color_or_season, "нежный")

    cleaned_flowers: List[str] = []
    for p in positions or []:
        raw = str(p.get("name", ""))
        if any(ex in raw.lower() for ex in EXCLUDE_WORDS):
            continue
        clean = clean_flower_name(raw)
        if clean and clean.lower() not in {c.lower() for c in cleaned_flowers}:
            cleaned_flowers.append(clean)

    # Формируем 1-2 ключевых цветка для первого предложения (SEO-сниппет).
    # Роза — главный коммерческий компонент: если есть в составе, выводим первой.
    lead_list = list(cleaned_flowers)
    for i, fl in enumerate(lead_list):
        if "роза" in fl.lower() or fl.lower().startswith("роз "):
            lead_list.insert(0, lead_list.pop(i))
            break
    if len(lead_list) >= 2:
        from platform_rules import _instrumental
        lead_flowers = f" с {_instrumental(lead_list[0])}, {_instrumental(lead_list[1])}"
    elif len(lead_list) == 1:
        from platform_rules import _instrumental
        lead_flowers = f" с {_instrumental(lead_list[0])}"
    else:
        lead_flowers = ""

    composition_str = (
        ", ".join(cleaned_flowers)
        if cleaned_flowers
        else "свежие сезонные цветы утренней поставки"
    )
    pack_label = "матовая упаковка" if packaging_type == "Пленка" else "под атласную ленту"
    care_text = build_individual_care(cleaned_flowers)

    lead_geo = "" if market else " в Санкт-Петербурге"
    br = "<br><br>" if market else "\n\n"
    return (
        f"{type_label} {mood} букет «{bouquet_name}»{lead_flowers} "
        f"от цветочной студии с азиатским характером REN{lead_geo}.{br}"
        f"{'🌿 ' if not market else ''}Цветы от сердца: мы создаём композиции на стыке современного минимализма и "
        f"азиатской эстетики — с воздухом, природной пластикой стеблей и тонким балансом оттенков. "
        f"Как и любое живое искусство, каждый наш букет неповторим: живые цветы обладают своим "
        f"характером и изгибом, поэтому флорист собирает каждую композицию вручную как единственную "
        f"в своём роде, сохраняя настроение и палитру задумки.{br}"
        f"{'🎁 ' if not market else ''}Идеальный подарок ко Дню матери, чтобы поблагодарить и порадовать любимую маму, "
        f"а также поздравить девушку, жену, подругу или коллегу с днём рождения, юбилеем, "
        f"свиданием или сделать тёплый комплимент без повода.{br}"
        f"{'💐 ' if not market else ''}Состав: {composition_str}.{br}"
        f"{'✨ ' if not market else ''}Оформление: {pack_label}.{br}"
        f"{'💧 ' if not market else ''}Как ухаживать: {care_text}{br}"
        + ("Перед передачей букет упаковывается в защитную транспортировочную упаковку — "
           "цветы сохраняют свежесть, форму и настроение композиции."
           if market else
           "🚚 Бережная доставка цветов по Санкт-Петербургу (СПб): привезём букет в защитной "
           "транспортировочной упаковке, а при необходимости дополнительно оформим в коробку "
           "с водой, чтобы цветы доехали безупречно свежими.")
    )
